const Z = (n) => String(n).replace(/[0-9]/g, (d) => String.fromCharCode(d.charCodeAt(0) + 0xFEE0));

const body = [];
articles.forEach(([cap, paras], ai) => {
  body.push(p(`（${cap}）`, { before: 160, keepNext: true, indent: { left: 210 } }));
  paras.forEach((para, pi) => {
    const text = typeof para === 'string' ? para : para.text;
    const label = pi === 0 ? `第${Z(ai + 1)}条　` : `${Z(pi + 1)}　`;
    body.push(p(label + text, { indent: { left: 210, hanging: 210 } }));
    (para.items || []).forEach((it, ii) => {
      body.push(p(`（${Z(ii + 1)}）` + it, { indent: { left: 840, hanging: 630 } }));
    });
  });
});

const d = doc([{
  pageNumber: true,
  children: [
    center(`${SCHOOL}ボランティア受入規程`, { size: 30, bold: true, gothic: true, after: 120 }),
    right('制定　　　　年　　月　　日'),
    ...blank(1),
    ...body,
    ...blank(1),
    p('附　則', { before: 120, keepNext: true, indent: { left: 840 } }),
    p('この規程は、　　　　年　　月　　日から施行する。', { indent: { firstLine: 210 } }),
  ],
}]);

