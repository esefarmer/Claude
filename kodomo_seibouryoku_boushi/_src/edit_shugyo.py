amend = []   # 新旧対照表用: {"jo":条, "old":[...], "new":[...], "note":理由}


def find(prefix):
    hits = [i for i, p in enumerate(paras) if text_of(p).strip().startswith(prefix)]
    assert len(hits) == 1, (prefix, hits)
    return hits[0]


ops = {}   # index -> list of replacement paragraph xml (置換) / 追加は後ろに連結


def replace(prefix, new_xml, jo, note):
    i = find(prefix)
    ops[i] = new_xml
    amend.append({"jo": jo, "old": [text_of(paras[i]).strip()],
                  "new": [text_of(n).strip() for n in new_xml], "note": note})


def insert_after(prefix, new_xml, jo, note):
    i = find(prefix)
    ops[i] = ops.get(i, [paras[i]]) + new_xml
    amend.append({"jo": jo, "old": ["（新設）"],
                  "new": [text_of(n).strip() for n in new_xml], "note": note})


